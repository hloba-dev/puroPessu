import type {Metadata} from 'next';
import {getPathname} from '@/i18n/navigation';
import {defaultLocale, locales, type Locale} from '@/i18n/routing';
import {BRAND, SITE_URL} from '@/lib/site';

export type Href = Parameters<typeof getPathname>[0]['href'];
/** One href for all locales, or a per-locale map when dynamic segments differ (blog slugs). */
export type LocalizedHref = Href | Record<Locale, Href>;

function hrefFor(href: LocalizedHref, locale: Locale): Href {
  if (typeof href === 'object' && href !== null && 'fi' in href) return (href as Record<Locale, Href>)[locale];
  return href as Href;
}

/** Site-relative localized path, e.g. `/ru/ceny`. */
export function localizedPath(href: LocalizedHref, locale: Locale) {
  return getPathname({href: hrefFor(href, locale), locale});
}

/** Absolute localized URL, e.g. `https://puropesu.fi/ru/ceny`. */
export function localizedUrl(href: LocalizedHref, locale: Locale) {
  const path = localizedPath(href, locale);
  return `${SITE_URL}${path === '/' ? '' : path}`;
}

export function hreflangAlternates(href: LocalizedHref, locale: Locale): NonNullable<Metadata['alternates']> {
  const languages: Record<string, string> = {};
  for (const l of locales) languages[l] = localizedUrl(href, l);
  languages['x-default'] = localizedUrl(href, defaultLocale);
  return {canonical: localizedUrl(href, locale), languages};
}

const ogLocale: Record<Locale, string> = {fi: 'fi_FI', ru: 'ru_RU', en: 'en_US'};

// Default social image (generated by `npm run icons`). Pages whose segment has an opengraph-image.tsx
// pass `ownOgImage` so the generated card (title + "from" price) is used instead.
const DEFAULT_OG_IMAGE = {url: `${SITE_URL}/og-default.png`, width: 1200, height: 630, alt: `${BRAND} — puropesu.fi`};

interface PageMeta {
  locale: Locale;
  href: LocalizedHref;
  title: string;
  description: string;
  /** Use the title as is, without the "| Puro" template */
  absoluteTitle?: boolean;
  noindex?: boolean;
  /** the route segment has its own opengraph-image.tsx: leave the image to the file convention */
  ownOgImage?: boolean;
  type?: 'website' | 'article';
  publishedTime?: string;
  modifiedTime?: string;
}

/** Title, description, canonical, hreflang, Open Graph and Twitter card for one page. */
export function pageMetadata({
  locale,
  href,
  title,
  description,
  absoluteTitle,
  noindex,
  ownOgImage,
  type = 'website',
  publishedTime,
  modifiedTime
}: PageMeta): Metadata {
  const url = localizedUrl(href, locale);
  // the brand suffix is dropped when it would push the title past what search results display
  const branded = `${title} | ${BRAND}`;
  const fullTitle = absoluteTitle || title.includes(`| ${BRAND}`) || branded.length > 65 ? title : branded;
  return {
    title: {absolute: fullTitle},
    description,
    alternates: noindex ? undefined : hreflangAlternates(href, locale),
    robots: noindex ? {index: false, follow: false} : undefined,
    openGraph: {
      type,
      url,
      title: fullTitle,
      description,
      siteName: BRAND,
      locale: ogLocale[locale],
      alternateLocale: locales.filter((l) => l !== locale).map((l) => ogLocale[l]),
      ...(ownOgImage ? {} : {images: [DEFAULT_OG_IMAGE]}),
      ...(type === 'article' ? {publishedTime, modifiedTime} : {})
    },
    twitter: {card: 'summary_large_image', title: fullTitle, description, ...(ownOgImage ? {} : {images: [DEFAULT_OG_IMAGE.url]})}
  };
}
