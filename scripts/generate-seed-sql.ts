/**
 * Generates supabase/seed.sql from src/lib/data/seed-data.ts so the SQL seed and the
 * demo-mode fallback can never drift apart.
 * Usage: npm run db:seed:generate
 */
import {writeFile} from 'node:fs/promises';
import path from 'node:path';
import {
  seedCategories,
  seedDraftReviews,
  seedGallery,
  seedServices,
  seedSettings
} from '../src/lib/data/seed-data';
import {settingsToRows} from '../src/lib/data/mappers';

const q = (value: string) => `'${value.replace(/'/g, "''")}'`;
const j = (value: unknown) => `${q(JSON.stringify(value))}::jsonb`;

const lines: string[] = [
  '-- Generated by scripts/generate-seed-sql.ts from src/lib/data/seed-data.ts. Do not edit by hand.',
  '-- Safe to re-run: catalog rows are matched by slug/key and never overwrite prices edited in /admin.',
  ''
];

lines.push('-- categories');
lines.push('insert into public.service_categories (id, slug, name, sort, is_active) values');
lines.push(
  seedCategories.map((c) => `  (${c.id}, ${q(c.slug)}, ${j(c.name)}, ${c.sort}, ${c.isActive})`).join(',\n')
);
lines.push('on conflict (slug) do nothing;', '');

lines.push('-- services');
lines.push(
  'insert into public.services (id, category_id, slug, name, description, price_cents, price_from, unit, duration_min, is_small, is_addon, is_active, sort) values'
);
lines.push(
  seedServices
    .map(
      (s) =>
        `  (${s.id}, ${s.categoryId}, ${q(s.slug)}, ${j(s.name)}, ${j(s.description)}, ${s.priceCents}, ${s.priceFrom}, ${q(s.unit)}, ${s.durationMin}, ${s.isSmall}, ${s.isAddon}, ${s.isActive}, ${s.sort})`
    )
    .join(',\n')
);
lines.push('on conflict (slug) do nothing;', '');

lines.push('-- per-item options (protection, leather care, odor removal)');
lines.push('insert into public.service_options (id, service_id, slug, name, price_cents, duration_min) values');
lines.push(
  seedServices
    .flatMap((s) => s.options)
    .map((o) => `  (${o.id}, ${o.serviceId}, ${q(o.slug)}, ${j(o.name)}, ${o.priceCents}, ${o.durationMin})`)
    .join(',\n')
);
lines.push('on conflict (service_id, slug) do nothing;', '');

lines.push('-- keep identity sequences ahead of the explicit ids above');
for (const table of ['service_categories', 'services', 'service_options']) {
  lines.push(
    `select setval(pg_get_serial_sequence('public.${table}', 'id'), (select max(id) from public.${table}));`
  );
}
lines.push('');

lines.push('-- settings (contacts are placeholders: edit them in /admin → Настройки)');
lines.push('insert into public.settings (key, value) values');
lines.push(
  settingsToRows(seedSettings)
    .map((row) => `  (${q(row.key)}, ${j(row.value)})`)
    .join(',\n')
);
lines.push('on conflict (key) do nothing;', '');

lines.push('-- one cleaner by default; add more in /admin to open parallel slots');
lines.push(
  "insert into public.staff (name) select 'Puro' where not exists (select 1 from public.staff);",
  ''
);

lines.push('-- demo before/after pairs (placeholders in public/images/before-after)');
lines.push('insert into public.gallery_items (before_url, after_url, caption, service_slug, sort, is_featured)');
lines.push('select v.* from (values');
lines.push(
  seedGallery
    .map(
      (g) =>
        `  (${q(g.beforeUrl)}, ${q(g.afterUrl)}, ${j(g.caption)}, ${q(g.serviceSlug)}, ${g.sort}, ${g.isFeatured})`
    )
    .join(',\n')
);
lines.push(') as v where not exists (select 1 from public.gallery_items);', '');

lines.push('-- demo reviews are drafts (is_published = false): they never appear on the site or in JSON-LD');
lines.push('insert into public.reviews (author, rating, text, locale, source, is_published)');
lines.push('select v.* from (values');
lines.push(
  seedDraftReviews
    .map((r) => `  (${q(r.author)}, ${r.rating}, ${q(r.text)}, ${q(r.locale)}, ${q(r.source)}::public.review_source, false)`)
    .join(',\n')
);
lines.push(') as v where not exists (select 1 from public.reviews);', '');

writeFile(path.join(process.cwd(), 'supabase/seed.sql'), lines.join('\n')).then(() =>
  console.log('supabase/seed.sql written')
);
