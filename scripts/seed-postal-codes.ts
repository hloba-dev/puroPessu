/**
 * Builds the postal code table (Uusimaa and the surrounding regions) from the open
 * Paavo data of Statistics Finland (geo.stat.fi, CC BY 4.0).
 *
 * Usage: npm run db:postal-codes
 * Writes  src/lib/data/postal-codes.json   (demo-mode fallback)
 *         supabase/seeds/postal_codes.sql  (seed for the `postal_codes` table)
 */
import {mkdir, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {seedSettings} from '../src/lib/data/seed-data';
import {haversineKm} from '../src/lib/booking/travel';

const WFS = 'https://geo.stat.fi/geoserver';
const MAX_STRAIGHT_KM = 200;

interface Feature<T> {
  properties: T;
}

async function fetchAll<T>(workspace: string, typeName: string, properties: string): Promise<T[]> {
  const url = `${WFS}/${workspace}/wfs?service=WFS&version=2.0.0&request=GetFeature&typeNames=${typeName}&outputFormat=application/json&propertyName=${properties}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${typeName}: HTTP ${res.status}`);
  const json = (await res.json()) as {features: Feature<T>[]};
  return json.features.map((f) => f.properties);
}

/** ETRS-TM35FIN (EPSG:3067) → WGS84. Inverse transverse Mercator on GRS80, zone 35 (central meridian 27°E). */
function tm35finToWgs84(easting: number, northing: number) {
  const a = 6378137;
  const f = 1 / 298.257222101;
  const k0 = 0.9996;
  const e2 = f * (2 - f);
  const ep2 = e2 / (1 - e2);
  const x = easting - 500000;
  const m = northing / k0;
  const mu = m / (a * (1 - e2 / 4 - (3 * e2 ** 2) / 64 - (5 * e2 ** 3) / 256));
  const e1 = (1 - Math.sqrt(1 - e2)) / (1 + Math.sqrt(1 - e2));
  const phi1 =
    mu +
    ((3 * e1) / 2 - (27 * e1 ** 3) / 32) * Math.sin(2 * mu) +
    ((21 * e1 ** 2) / 16 - (55 * e1 ** 4) / 32) * Math.sin(4 * mu) +
    ((151 * e1 ** 3) / 96) * Math.sin(6 * mu) +
    ((1097 * e1 ** 4) / 512) * Math.sin(8 * mu);
  const sin1 = Math.sin(phi1);
  const cos1 = Math.cos(phi1);
  const tan1 = Math.tan(phi1);
  const c1 = ep2 * cos1 ** 2;
  const t1 = tan1 ** 2;
  const n1 = a / Math.sqrt(1 - e2 * sin1 ** 2);
  const r1 = (a * (1 - e2)) / (1 - e2 * sin1 ** 2) ** 1.5;
  const d = x / (n1 * k0);
  const lat =
    phi1 -
    ((n1 * tan1) / r1) *
      (d ** 2 / 2 -
        ((5 + 3 * t1 + 10 * c1 - 4 * c1 ** 2 - 9 * ep2) * d ** 4) / 24 +
        ((61 + 90 * t1 + 298 * c1 + 45 * t1 ** 2 - 252 * ep2 - 3 * c1 ** 2) * d ** 6) / 720);
  const lng =
    (27 * Math.PI) / 180 +
    (d -
      ((1 + 2 * t1 + c1) * d ** 3) / 6 +
      ((5 - 2 * c1 + 28 * t1 - 3 * c1 ** 2 + 8 * ep2 + 24 * t1 ** 2) * d ** 5) / 120) /
      cos1;
  return {lat: (lat * 180) / Math.PI, lng: (lng * 180) / Math.PI};
}

const sql = (value: string) => `'${value.replace(/'/g, "''")}'`;

async function main() {
  const [areas, municipalities] = await Promise.all([
    fetchAll<{postinumeroalue: string; kunta: string; euref_x: number; euref_y: number}>(
      'postialue',
      'postialue:pno_tilasto',
      'postinumeroalue,kunta,euref_x,euref_y'
    ),
    fetchAll<{kunta: string; nimi: string}>('tilastointialueet', 'tilastointialueet:kunta4500k', 'kunta,nimi')
  ]);
  const municipalityName = new Map(municipalities.map((m) => [m.kunta, m.nimi]));

  const rows = areas
    .map((area) => {
      const {lat, lng} = tm35finToWgs84(area.euref_x, area.euref_y);
      return {
        code: area.postinumeroalue,
        municipality: municipalityName.get(area.kunta) ?? area.kunta,
        lat: Math.round(lat * 1e5) / 1e5,
        lng: Math.round(lng * 1e5) / 1e5
      };
    })
    .filter((row) => haversineKm(seedSettings.baseLat, seedSettings.baseLng, row.lat, row.lng) <= MAX_STRAIGHT_KM)
    .sort((x, y) => x.code.localeCompare(y.code));

  const root = process.cwd();
  await writeFile(
    path.join(root, 'src/lib/data/postal-codes.json'),
    JSON.stringify(rows.map((r) => [r.code, r.municipality, r.lat, r.lng]))
  );

  await mkdir(path.join(root, 'supabase/seeds'), {recursive: true});
  const values = rows.map((r) => `(${sql(r.code)}, ${sql(r.municipality)}, ${r.lat}, ${r.lng})`).join(',\n');
  await writeFile(
    path.join(root, 'supabase/seeds/postal_codes.sql'),
    `-- Generated by scripts/seed-postal-codes.ts from Statistics Finland Paavo data (CC BY 4.0). Do not edit by hand.\n` +
      `insert into public.postal_codes (code, municipality, lat, lng) values\n${values}\n` +
      `on conflict (code) do update set municipality = excluded.municipality, lat = excluded.lat, lng = excluded.lng;\n`
  );

  console.log(`${rows.length} postal codes within ${MAX_STRAIGHT_KM} km of the base written.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
