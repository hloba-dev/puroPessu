/**
 * Bundles migrations + seeds into one file, supabase/setup.sql, for people who set the
 * database up by pasting SQL into the Supabase dashboard (SQL Editor) instead of using the CLI.
 * Usage: npm run db:bundle
 */
import {readdirSync, readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';

const root = path.join(process.cwd(), 'supabase');
const files = [
  ...readdirSync(path.join(root, 'migrations'))
    .sort()
    .map((file) => path.join('migrations', file)),
  'seed.sql',
  path.join('seeds', 'postal_codes.sql')
];

const header = `-- Puro: complete database setup (schema, security, storage, seed data).
-- Generated by scripts/bundle-sql.ts — do not edit; change the migrations / seed and run \`npm run db:bundle\`.
-- Run ONCE on a new Supabase project: Dashboard → SQL Editor → paste this file → Run.
`;

const body = files
  .map((file) => `\n-- ==================== ${file} ====================\n${readFileSync(path.join(root, file), 'utf8').trim()}\n`)
  .join('');

writeFileSync(path.join(root, 'setup.sql'), header + body);
console.log(`supabase/setup.sql written (${files.length} files, ${Math.round((header + body).length / 1024)} KB)`);
