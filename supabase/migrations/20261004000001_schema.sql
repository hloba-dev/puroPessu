-- Puro: core schema
create schema if not exists extensions;
create extension if not exists btree_gist with schema extensions;
set search_path = public, extensions;

create type public.service_unit as enum ('item', 'piece', 'm2');
create type public.booking_status as enum ('pending', 'confirmed', 'done', 'cancelled');
create type public.customer_type as enum ('private', 'business');
create type public.quote_sector as enum ('office', 'hotel_restaurant', 'healthcare', 'carpet', 'other');
create type public.preferred_time as enum ('workhours', 'evening', 'weekend', 'flexible');
create type public.gift_card_status as enum ('requested', 'paid', 'redeemed', 'expired');
create type public.review_source as enum ('google', 'site');
create type public.request_status as enum ('new', 'in_progress', 'done');

-- ---------- catalog: the single source of prices ----------

create table public.service_categories (
  id int generated by default as identity primary key,
  slug text not null unique,
  name jsonb not null,
  sort int not null default 0,
  is_active boolean not null default true
);

create table public.services (
  id int generated by default as identity primary key,
  category_id int not null references public.service_categories (id) on delete restrict,
  slug text not null unique,
  name jsonb not null,
  description jsonb not null default '{}'::jsonb,
  price_cents int not null check (price_cents >= 0),
  price_from boolean not null default false,
  unit public.service_unit not null default 'item',
  duration_min int not null default 0 check (duration_min >= 0),
  is_small boolean not null default false,
  -- price-list-only rows (e.g. protection): booked as per-item options, not as separate lines
  is_addon boolean not null default false,
  is_active boolean not null default true,
  sort int not null default 0
);
create index services_category_idx on public.services (category_id);

create table public.service_options (
  id int generated by default as identity primary key,
  service_id int not null references public.services (id) on delete cascade,
  slug text not null,
  name jsonb not null,
  price_cents int not null check (price_cents >= 0),
  duration_min int not null default 0 check (duration_min >= 0),
  unique (service_id, slug)
);

create table public.settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);

create table public.postal_codes (
  code text primary key check (code ~ '^[0-9]{5}$'),
  municipality text not null,
  lat double precision not null,
  lng double precision not null
);

create table public.staff (
  id int generated by default as identity primary key,
  name text not null,
  is_active boolean not null default true
);

-- ---------- gift cards ----------

create table public.gift_cards (
  id uuid primary key default gen_random_uuid(),
  -- assigned when the card is marked as paid
  code text unique,
  amount_cents int check (amount_cents > 0),
  -- what is left of a value card: starts at amount_cents, each booking takes its discount from it
  balance_cents int check (balance_cents >= 0),
  service_id int references public.services (id) on delete set null,
  buyer_name text not null,
  buyer_email text not null,
  buyer_phone text,
  recipient_name text,
  message text,
  locale text not null default 'fi' check (locale in ('fi', 'ru', 'en')),
  status public.gift_card_status not null default 'requested',
  valid_until date,
  redeemed_booking_id uuid,
  created_at timestamptz not null default now(),
  check (amount_cents is not null or service_id is not null)
);

-- ---------- bookings ----------

create table public.bookings (
  id uuid primary key default gen_random_uuid(),
  ref_code text not null unique,
  locale text not null default 'fi' check (locale in ('fi', 'ru', 'en')),
  status public.booking_status not null default 'pending',
  customer_type public.customer_type not null default 'private',
  name text not null,
  phone text not null,
  email text not null,
  company text,
  y_tunnus text,
  address text not null,
  postal_code text not null,
  city text not null,
  floor text,
  parking text,
  notes text,
  starts_at timestamptz not null,
  -- end of the busy interval: work duration + travel buffer
  ends_at timestamptz not null,
  -- estimated work duration shown to the customer
  duration_min int not null check (duration_min > 0),
  staff_id int not null references public.staff (id),
  subtotal_cents int not null check (subtotal_cents >= 0),
  travel_cents int not null default 0 check (travel_cents >= 0),
  min_fill_cents int not null default 0 check (min_fill_cents >= 0),
  -- promotion taken off the price: bundle offer and/or percentage discount (details in promo_details)
  promo_cents int not null default 0 check (promo_cents >= 0),
  promo_details jsonb not null default '{}'::jsonb,
  -- gift card amount used
  discount_cents int not null default 0 check (discount_cents >= 0),
  total_cents int not null check (total_cents >= 0),
  gift_card_code text,
  -- photos attached by the customer: object paths in the private `booking-photos` bucket
  photos text[] not null default '{}' check (cardinality(photos) <= 10),
  marketing_consent boolean not null default false,
  manage_token text not null unique,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at),
  -- one cleaner cannot be in two places: active bookings of the same staff member never overlap
  constraint bookings_no_overlap exclude using gist (
    staff_id with =,
    tstzrange(starts_at, ends_at, '[)') with &&
  ) where (status in ('pending', 'confirmed'))
);
create index bookings_starts_idx on public.bookings (starts_at);
create index bookings_status_idx on public.bookings (status);
create index bookings_created_idx on public.bookings (created_at desc);
-- first order or returning customer? looked up by e-mail and phone
create index bookings_email_idx on public.bookings (lower(email));
create index bookings_phone_idx on public.bookings (phone);

alter table public.gift_cards
  add constraint gift_cards_redeemed_booking_fk
  foreign key (redeemed_booking_id) references public.bookings (id) on delete set null;

create table public.booking_items (
  id bigint generated always as identity primary key,
  booking_id uuid not null references public.bookings (id) on delete cascade,
  service_id int references public.services (id) on delete set null,
  -- snapshots: the booking stays readable even if the catalog changes later
  service_slug text not null,
  name text not null,
  option_ids int[] not null default '{}',
  option_slugs text[] not null default '{}',
  qty int not null check (qty > 0),
  -- per unit, options included
  unit_price_cents int not null check (unit_price_cents >= 0),
  duration_min int not null default 0,
  very_dirty boolean not null default false
);
create index booking_items_booking_idx on public.booking_items (booking_id);

create table public.blocked_times (
  id uuid primary key default gen_random_uuid(),
  -- null = blocks every staff member (holiday, vacation)
  staff_id int references public.staff (id) on delete cascade,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  reason text,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at)
);
create index blocked_times_range_idx on public.blocked_times (starts_at, ends_at);

